import type { EffectDef } from './core/types.ts';
import { GRID_EFFECTS } from './effects/grid.ts';
import { TILE_EFFECTS } from './effects/tile.ts';
import { PIXEL_EFFECTS } from './effects/pixel.ts';
import { DITHER_EFFECTS } from './effects/dither.ts';
import { DISTORT_EFFECTS } from './effects/distort.ts';
import { BLUR_EFFECTS } from './effects/blurs.ts';
import { SIGNAL_EFFECTS } from './effects/signal.ts';
import { PRINT_EFFECTS } from './effects/print.ts';
import { STIPPLE_EFFECTS } from './effects/stipple.ts';
import { PHASE2_EFFECTS } from './effects/phase2.ts';
import { VOXEL_EFFECTS } from './effects/voxel.ts';
import { LIGHT_EFFECTS } from './effects/light.ts';
export const EFFECTS: EffectDef[] = [...GRID_EFFECTS, ...TILE_EFFECTS, ...PIXEL_EFFECTS, ...DITHER_EFFECTS, ...DISTORT_EFFECTS, ...BLUR_EFFECTS, ...SIGNAL_EFFECTS, ...PRINT_EFFECTS, ...STIPPLE_EFFECTS, ...PHASE2_EFFECTS, ...VOXEL_EFFECTS, ...LIGHT_EFFECTS];
const byId = new Map(EFFECTS.map((e) => [e.id, e]));
if (byId.size !== EFFECTS.length) throw new Error('duplicate effect id in registry');
export const getEffect = (id: string): EffectDef => { const e = byId.get(id); if (!e) throw new Error(`unknown effect "${id}"`); return e; };
